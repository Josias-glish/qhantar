"""Walk a NISAR GUNW HDF5 file and write what is actually inside it to Markdown.

Usage: python scripts/inspect_gunw.py data/raw/<granule>.h5 docs/product-inspection.md
"""
import sys
from pathlib import Path

import h5py
import numpy as np

KEEP_ATTRS = ("units", "_FillValue", "description", "long_name", "valid_min", "valid_max",
              "grid_mapping", "epsg_code", "spatial_ref", "flag_meanings", "flag_values")


def fmt(v, n=160):
    if isinstance(v, bytes):
        v = v.decode(errors="replace")
    if isinstance(v, np.ndarray):
        if v.dtype.kind == "S":
            v = [x.decode(errors="replace") for x in v.ravel()]
        else:
            v = v.tolist()
    s = str(v).replace("\n", " ").replace("|", "\\|")
    return s if len(s) <= n else s[:n] + "…"


def main(src, dst):
    lines = [f"# Product inspection\n", f"File: `{Path(src).name}`\n",
             "Generated by `scripts/inspect_gunw.py` from the file itself.\n"]
    rows, scalars = [], []
    with h5py.File(src, "r") as f:
        lines.append("## Root attributes\n")
        for k, v in f.attrs.items():
            lines.append(f"- `{k}`: {fmt(v)}")

        def visit(name, obj):
            if not isinstance(obj, h5py.Dataset):
                return
            attrs = "; ".join(f"{k}={fmt(obj.attrs[k], 80)}" for k in KEEP_ATTRS if k in obj.attrs)
            rows.append(f"| `/{name}` | {obj.shape} | {obj.dtype} | {attrs} |")
            if obj.size <= 4 and obj.dtype.kind in "SOiuf":
                scalars.append(f"| `/{name}` | {fmt(obj[()])} |")
            elif obj.ndim == 1 and obj.size >= 2 and obj.dtype.kind in "iuf" and ("Coordinates" in name or "height" in name.lower()):
                a = obj[()]
                scalars.append(f"| `/{name}` (axis) | first={a[0]}, last={a[-1]}, step={a[1]-a[0]}, n={a.size} |")

        f.visititems(visit)
    lines += ["\n## Datasets\n", "| Path | Shape | Type | Attributes |", "| --- | --- | --- | --- |", *rows]
    lines += ["\n## Small values and coordinate axes\n", "| Path | Value |", "| --- | --- |", *scalars]
    Path(dst).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} datasets written to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
